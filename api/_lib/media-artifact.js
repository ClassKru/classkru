'use strict';
const crypto = require('node:crypto');
const acorn = require('acorn');
const { parseFragment, serialize } = require('parse5');
const { fail } = require('./media-db');
const POLICY_VERSION = 1;
const TAGS = new Set('div span p h1 h2 h3 h4 section article header footer main aside strong em small b i br hr ul ol li label button input select option textarea output progress meter table caption thead tbody tr th td canvas svg g path rect circle ellipse line polyline polygon text tspan defs linearGradient radialGradient stop title desc'.toLowerCase().split(' '));
const ATTRS = new Set('id class title role tabindex type min max step value checked disabled selected placeholder width height viewbox d x y x1 x2 y1 y2 cx cy r rx ry fill stroke stroke-width points transform opacity offset stop-color for name rows cols maxlength'.split(' '));
function escape(value) { return String(value).replace(/[&<>"']/g, c => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;' }[c])); }
function validateArtifact(input) {
  if (!input || typeof input !== 'object') throw fail('invalid_artifact');
  const limits = { title: 120, summary: 1200, html: 65000, css: 32000, js: 85000 };
  const artifact = {};
  for (const [key, max] of Object.entries(limits)) {
    if (typeof input[key] !== 'string' || (key!=='js'&&!input[key].trim()) || Buffer.byteLength(input[key]) > max) throw fail('invalid_artifact');
    artifact[key] = input[key];
  }
  const root = parseFragment(artifact.html);
  let elements = 0;
  function walk(node) {
    if (node.tagName) {
      if (++elements > 1200 || !TAGS.has(node.tagName.toLowerCase())) throw fail('unsafe_html');
      for (const attr of node.attrs || []) {
        if (attr.namespace || (!ATTRS.has(attr.name.toLowerCase()) && !/^aria-[a-z-]+$/.test(attr.name) && !/^data-[a-z-]+$/.test(attr.name))) throw fail('unsafe_html');
        if (/(?:url\s*\(|javascript:|https?:|\/\/)/i.test(attr.value)) throw fail('unsafe_html');
      }
      if (node.tagName === 'input' && (node.attrs || []).some(a => a.name === 'type' && /^(?:file|password|email|image)$/i.test(a.value))) throw fail('unsafe_html');
    }
    for (const child of node.childNodes || []) walk(child);
  }
  walk(root);
  artifact.html = serialize(root);
  if (/<\/style|@import|url\s*\(|expression\s*\(/i.test(artifact.css)) throw fail('unsafe_css');
  if (/<\/script/i.test(artifact.js)) throw fail('unsafe_script');
  let ast;
  try { ast = acorn.parse(artifact.js, { ecmaVersion: 2022, sourceType: 'script' }); }
  catch (_) { throw fail('invalid_javascript'); }
  // Defense in depth only. CSP + opaque sandbox are the actual trust boundary.
  const forbidden = new Set('eval Function fetch XMLHttpRequest WebSocket EventSource Worker SharedWorker localStorage sessionStorage indexedDB open parent top opener location navigator importScripts'.split(' '));
  function inspect(node) {
    if (!node || typeof node !== 'object') return;
    if (node.type === 'ImportExpression' || (node.type === 'Identifier' && forbidden.has(node.name))) throw fail('unsafe_script');
    for (const value of Object.values(node)) {
      if (Array.isArray(value)) value.forEach(inspect);
      else if (value && typeof value === 'object') inspect(value);
    }
  }
  inspect(ast);
  return artifact;
}
function hash(artifact) { return crypto.createHash('sha256').update(JSON.stringify(artifact)).digest('hex'); }
function render(artifact) {
  const nonce = crypto.randomBytes(24).toString('base64');
  const csp = `default-src 'none'; script-src 'nonce-${nonce}'; style-src 'nonce-${nonce}' 'unsafe-inline'; img-src data: blob:; font-src 'none'; media-src 'none'; connect-src 'none'; frame-src 'none'; worker-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'; sandbox allow-scripts`;
  // Style attributes generated by trusted browser APIs are useful; nonce CSS is the entry point.
  const html = `<!doctype html><html lang="th"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="${escape(csp.replace('; sandbox allow-scripts', ''))}"><title>${escape(artifact.title)}</title><style nonce="${nonce}">*{box-sizing:border-box}body{margin:0;font-family:system-ui,sans-serif;overflow-wrap:anywhere}button,input,select{font:inherit}${artifact.css}</style></head><body>${artifact.html}<script nonce="${nonce}">${artifact.js}</script></body></html>`;
  return { html, csp, policy_version: POLICY_VERSION };
}
module.exports = { validateArtifact, hash, render, POLICY_VERSION };
