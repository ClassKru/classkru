'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const briefs = path.join(root, 'classkru ai chat/briefs');
const registry = JSON.parse(fs.readFileSync(path.join(briefs, 'registry.json'), 'utf8'));
const versions = Object.fromEntries(registry.versions.map(({ id, label }) => {
  if (!/^[a-z0-9][a-z0-9_-]{0,39}$/i.test(id)) throw new Error('invalid_brief_version');
  const dir = path.join(briefs, 'versions', id);
  return [id, { id, label, config: JSON.parse(fs.readFileSync(path.join(dir, 'config.json'), 'utf8')), system: fs.readFileSync(path.join(dir, 'system.md'), 'utf8').replace(/\r\n/g, '\n').trim(), navigation: fs.readFileSync(path.join(dir, 'navigation.md'), 'utf8').replace(/\r\n/g, '\n').trim() }];
}));
const target = path.join(root, 'api/_lib/classkru-ai-briefs.cjs');
fs.writeFileSync(target, "'use strict';\n// Generated by scripts/pack-classkru-ai-briefs.cjs. Server only.\nmodule.exports = " + JSON.stringify({ registry, versions }, null, 2) + ';\n');
